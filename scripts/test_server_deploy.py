"""The server deployment (docs/deployment.md) against the stand it is built on: every secret of
deploy/compose.yaml is generated by apparatica-secrets, and every address of the stand that a server
serves under its public names is replaced by deploy/compose.server.yaml."""

import importlib.util
import re
import stat
import sys
from pathlib import Path
from types import ModuleType

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
DEPLOY = ROOT / "deploy"
GENERATOR = DEPLOY / "ansible" / "roles" / "apparatica" / "files" / "apparatica-secrets.py"

# A variable with a default, ${NAME:-value}.
DEFAULTED = re.compile(r"\$\{([A-Z0-9_]+):-([^}]*)\}")
SECRET_NAME = re.compile(r"PASSWORD|SECRET|_KEY$|_KEY_ID$|TOKEN|SALT")


def load_generator() -> ModuleType:
    spec = importlib.util.spec_from_file_location("apparatica_secrets", GENERATOR)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


generator = load_generator()


class Replaced(dict):  # type: ignore[type-arg]
    """A mapping under !override or !reset: it replaces that of compose.yaml as a whole."""


class ComposeLoader(yaml.SafeLoader):
    pass


def replaced(loader: yaml.SafeLoader, node: yaml.Node) -> object:
    if isinstance(node, yaml.MappingNode):
        return Replaced(loader.construct_mapping(node))
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node)
    return loader.construct_scalar(node)  # type: ignore[arg-type]


for tag in ("!override", "!reset"):
    ComposeLoader.add_constructor(tag, replaced)


def compose(name: str) -> dict:  # type: ignore[type-arg]
    text = (DEPLOY / name).read_text(encoding="utf-8")
    return yaml.load(text, Loader=ComposeLoader)  # type: ignore[no-any-return]


def test_every_secret_of_the_stand_is_generated() -> None:
    text = (DEPLOY / "compose.yaml").read_text(encoding="utf-8")
    secrets = {name for name, _ in DEFAULTED.findall(text) if SECRET_NAME.search(name)}
    assert secrets == set(generator.SECRETS)


def test_generated_values_suit_the_services(tmp_path: Path) -> None:
    path = tmp_path / "secrets.env"
    assert generator.complete(path) == list(generator.SECRETS)
    values = generator.read(path)
    for name, value in values.items():
        if name.endswith("_KEY_ID"):  # Garage: "GK" and 12 bytes in hex
            assert re.fullmatch(r"GK[0-9a-f]{24}", value), name
        else:  # hex: safe in URLs, the ACL file of Valkey and the Garage configuration
            assert re.fullmatch(r"[0-9a-f]{32,}", value), name
    assert len(values["GARAGE_RPC_SECRET"]) == 64
    if sys.platform != "win32":
        assert stat.S_IMODE(path.stat().st_mode) == 0o600


def test_existing_secrets_are_kept(tmp_path: Path) -> None:
    path = tmp_path / "secrets.env"
    path.write_text("POSTGRES_PASSWORD=kept\n", encoding="utf-8")
    added = generator.complete(path)
    assert "POSTGRES_PASSWORD" not in added
    assert generator.read(path)["POSTGRES_PASSWORD"] == "kept"
    before = path.read_text(encoding="utf-8")
    assert generator.complete(path) == []
    assert path.read_text(encoding="utf-8") == before


def stand_addresses(service: dict) -> set[str]:  # type: ignore[type-arg]
    environment = service.get("environment", {})
    if not isinstance(environment, dict):
        return set()
    return {name for name, value in environment.items() if "localhost" in str(value)}


@pytest.mark.parametrize("name", sorted(compose("compose.yaml")["services"]))
def test_the_server_replaces_the_addresses_of_the_stand(name: str) -> None:
    stand = compose("compose.yaml")["services"][name]
    server = compose("compose.server.yaml")["services"].get(name, {})
    environment = server.get("environment", {})
    if isinstance(environment, Replaced):
        return
    missing = stand_addresses(stand) - set(environment)
    assert not missing, f"{name}: {sorted(missing)} keep the address of the stand"
    if "extra_hosts" in stand:
        assert "extra_hosts" in server, f"{name}: extra_hosts of the stand"
