#!/usr/bin/env python3
"""Create the secrets of a server (docs/deployment.md#секреты): an env file for docker compose.

    apparatica-secrets /etc/apparatica/secrets.env

Every secret of deploy/compose.yaml gets a random value once; the values already in the file are
kept, so a secret added in a new release is generated on its first deploy. Prints the names it
added; nothing when the file was complete. Standard library only: it runs on the server.
"""

import os
import secrets
import sys
from collections.abc import Callable
from pathlib import Path


def hex_bytes(n: int) -> Callable[[], str]:
    return lambda: secrets.token_hex(n)


def garage_key_id() -> str:
    return "GK" + secrets.token_hex(12)


SECRETS: dict[str, Callable[[], str]] = {
    "POSTGRES_PASSWORD": hex_bytes(24),
    "VALKEY_QUEUE_API_PASSWORD": hex_bytes(24),
    "VALKEY_QUEUE_WORKER_PASSWORD": hex_bytes(24),
    "VALKEY_QUEUE_INGEST_PASSWORD": hex_bytes(24),
    "APX_JOB_TOKEN_KEY": hex_bytes(32),
    "APX_GUEST_COOKIE_KEY": hex_bytes(32),
    "APX_IP_HASH_SALT": hex_bytes(32),
    "APX_CAPTCHA_KEY": hex_bytes(32),
    "GARAGE_RPC_SECRET": hex_bytes(32),
    "GARAGE_ADMIN_TOKEN": hex_bytes(32),
    "S3_API_KEY_ID": garage_key_id,
    "S3_API_KEY_SECRET": hex_bytes(32),
    "S3_WORKER_KEY_ID": garage_key_id,
    "S3_WORKER_KEY_SECRET": hex_bytes(32),
    "S3_INGEST_KEY_ID": garage_key_id,
    "S3_INGEST_KEY_SECRET": hex_bytes(32),
    "GRAFANA_ADMIN_PASSWORD": hex_bytes(16),
    # Encrypts the backups (libsodium): lost with the server, they cannot be read.
    "BACKUP_ENCRYPTION_KEY": hex_bytes(32),
}


def read(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    values = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            name, _, value = line.partition("=")
            values[name] = value
    return values


def complete(path: Path) -> list[str]:
    """Add the missing secrets to the file; return their names."""
    values = read(path)
    added = [name for name in SECRETS if name not in values]
    if not added:
        return []
    values.update({name: SECRETS[name]() for name in added})
    text = "# Generated by apparatica-secrets; keep a copy outside the server.\n"
    text += "".join(f"{name}={value}\n" for name, value in values.items())
    # Written next to the file and renamed: a failure never leaves half of it.
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    temporary.chmod(0o600)
    os.replace(temporary, path)
    return added


def main() -> int:
    for name in complete(Path(sys.argv[1])):
        print(name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
