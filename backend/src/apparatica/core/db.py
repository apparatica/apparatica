"""Database access: async SQLAlchemy engine, sessions and the declarative base (specs/04 §4).

Models of every module derive from `Base` and are collected by `apparatica.models`; Alembic
migrations (`apparatica.migrations`) compare against `Base.metadata`. Constraint names follow one
convention, so migrations are stable.
"""

import uuid
from collections.abc import AsyncIterator
from datetime import datetime
from typing import Any, ClassVar

from fastapi import Request
from sqlalchemy import DateTime, MetaData, Text, func, text
from sqlalchemy.dialects.postgresql import ARRAY, JSONB
from sqlalchemy.ext.asyncio import (
    AsyncEngine,
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)
from sqlalchemy.orm import DeclarativeBase, MappedColumn, mapped_column

from apparatica.core.ids import uuid7

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map: ClassVar[dict[Any, Any]] = {
        str: Text,
        datetime: DateTime(timezone=True),
        dict[str, Any]: JSONB,
        list[str]: ARRAY(Text),
    }


def uuid_pk() -> MappedColumn[uuid.UUID]:
    """UUIDv7 primary key, generated by the application (sortable by creation time)."""
    return mapped_column(primary_key=True, default=uuid7)


def created_at() -> MappedColumn[datetime]:
    return mapped_column(server_default=func.now())


class Database:
    def __init__(self, url: str) -> None:
        self.engine: AsyncEngine = create_async_engine(url, pool_pre_ping=True)
        self.sessions = async_sessionmaker(self.engine, expire_on_commit=False)

    async def ping(self) -> None:
        async with self.engine.connect() as connection:
            await connection.execute(text("SELECT 1"))

    async def dispose(self) -> None:
        await self.engine.dispose()


async def get_session(request: Request) -> AsyncIterator[AsyncSession]:
    """FastAPI dependency: one session per request, rolled back unless the handler commits."""
    database: Database = request.app.state.database
    async with database.sessions() as session:
        yield session
